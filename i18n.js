const LANG_KEY = "algoritmi-lang";
const DEFAULT_LANG = "bs";

function getLang() {
  const stored = localStorage.getItem(LANG_KEY);
  return stored === "en" || stored === "bs" ? stored : DEFAULT_LANG;
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  applyLanguage(lang);
}

function t(key, vars = {}) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  Object.keys(vars).forEach(k => {
    str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  });
  return str;
}

function applyLanguage(lang) {
  document.documentElement.lang = lang === "bs" ? "bs" : "en";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
    btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
  });
  const themeBtn = document.getElementById("theme-toggle");
  if (themeBtn) {
    const dark = document.documentElement.dataset.theme === "dark";
    themeBtn.setAttribute("aria-label", t(dark ? "theme.light" : "theme.dark"));
  }
  const langGroup = document.querySelector(".lang-switch");
  if (langGroup) langGroup.setAttribute("aria-label", t("lang.group"));
  if (typeof updateMenuToggleLabel === "function") updateMenuToggleLabel();
  if (typeof window.onLanguageChange === "function") window.onLanguageChange(lang);
}

window.getLang = getLang;
window.setLang = setLang;
window.t = t;
window.applyLanguage = applyLanguage;
